// Real ChatRoom with local socket/API doubles. Vite must serve this checkout on port 5180.
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const output = path.resolve(__dirname, '../../..', 'tmp/member-menu-check');
fs.mkdirSync(output, { recursive: true });
app.commandLine.appendSwitch('user-data-dir', path.join(output, 'profile'));
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const timeout = setTimeout(() => app.exit(1), 45000);
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1000, height: 760, show: false, webPreferences: { offscreen: true, backgroundThrottling: false } });
  win.webContents.setFrameRate(30);
  win.webContents.on('console-message', event => { if (event.level === 'error') console.error(event.message); });
  const js = code => win.webContents.executeJavaScript(code);
  const waitFor = async fn => { for (let i=0;i<80;i++){if(await fn())return;await delay(50);}throw new Error('UI wait timed out'); };
  const click = async (selector, button = 'left') => {
    const point = await js(`(() => {const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw new Error('Missing element');const r=e.getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)};})()`);
    win.webContents.sendInputEvent({ type: 'mouseDown', button, ...point, clickCount: 1 });
    win.webContents.sendInputEvent({ type: 'mouseUp', button, ...point, clickCount: 1 });
    await delay(100);
  };
  const alice = '[data-member-profile][title*="小雨"]';
  const open = async () => { await click(alice,'right'); await waitFor(()=>js('!!document.querySelector("[role=menu]")')); };
  try {
    await win.loadURL('http://127.0.0.1:5180/tests/ui/member-menu.html');
    await waitFor(()=>js('document.querySelectorAll("[data-member-profile]").length===3'));
    assert.equal(await js('[...document.querySelectorAll("aside button")].some(b=>["禁言","解禁","移出房间"].includes(b.textContent.trim()))'),false);
    await click('[data-member-profile][title="打开个人名片"]','right');
    assert.equal(await js('!!document.querySelector("[role=menu]")'),false);
    await click('[data-member-profile][title*="受保护房主"]','right');
    assert.equal(await js('!!document.querySelector("[role=menu]")'),false);
    await open();
    assert.deepEqual(await js('[...document.querySelectorAll("[role=menuitem]")].map(b=>b.textContent.trim())'),['禁言','移出房间']);
    fs.writeFileSync(path.join(output,'menu.png'),(await win.webContents.capturePage()).toPNG());
    await click('[role="menuitem"]');
    assert.deepEqual(await js('window.memberMenuTest.requests[0]'),{event:'room:set-muted',data:{roomId:'test',targetSocketId:'alice',muted:true}});
    await open();
    assert.equal(await js('document.querySelector("[role=menuitem]").textContent.trim()'),'解除禁言');
    await js('document.querySelector("[role=menu]").dispatchEvent(new KeyboardEvent("keydown",{key:"ArrowDown",bubbles:true}))');
    assert.equal(await js('document.activeElement.textContent.trim()'),'移出房间');
    await js('document.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}))');
    await waitFor(()=>js('!document.querySelector("[role=menu]")'));
    assert.equal(await js('document.activeElement.title.includes("小雨")'),true);
    await js(`document.querySelector(${JSON.stringify(alice)}).dispatchEvent(new KeyboardEvent('keydown',{key:'F10',shiftKey:true,bubbles:true,cancelable:true}))`);
    await waitFor(()=>js('!!document.querySelector("[role=menu]")'));
    await click('[role="menuitem"]');
    assert.equal(await js('window.memberMenuTest.requests[1].data.muted'),false);
    await open();
    await click('[role="menuitem"]:last-child');
    await waitFor(()=>js('!!document.querySelector("#kick-member-title")'));
    assert.equal(await js('window.memberMenuTest.requests.some(r=>r.event==="room:kick")'),false,'No kick before confirmation');
    await js('[...document.getElementById("kick-member-title").closest("section").querySelectorAll("button")].find(b=>b.textContent.includes("确认移除")).click()');
    await delay(80);
    assert.equal(await js('window.memberMenuTest.requests.find(r=>r.event==="room:kick").data.targetSocketId'),'alice');
    await js(`document.querySelector(${JSON.stringify(alice)}).dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:innerWidth-1,clientY:innerHeight-1}))`);
    await waitFor(()=>js('!!document.querySelector("[role=menu]")'));
    assert.equal(await js('(()=>{const r=document.querySelector("[role=menu]").getBoundingClientRect();return r.left>=8&&r.top>=8&&r.right<=innerWidth-7&&r.bottom<=innerHeight-7})()'),true);
    await js('document.body.dispatchEvent(new PointerEvent("pointerdown",{bubbles:true}))');
    await waitFor(()=>js('!document.querySelector("[role=menu]")'));
    await open();await js('window.memberMenuTest.setOwner(false)');
    await waitFor(()=>js('!document.querySelector("[role=menu]")'));
    await click(alice,'right');assert.equal(await js('!!document.querySelector("[role=menu]")'),false);
    await js('window.memberMenuTest.setOwner(true)');await delay(80);
    assert.equal(await js('!!document.querySelector("[role=menu]")'),false,'Lost authority clears menu state');
    await open();await js('window.memberMenuTest.removeAlice()');
    await waitFor(()=>js('!document.querySelector("[role=menu]")'));
    console.log('PASS: no inline moderation buttons; owner-only context menu, mute/unmute, confirmed kick, keyboard/outside dismissal, viewport clamping and invalid-target cleanup.');
    clearTimeout(timeout);win.destroy();app.exit(0);
  } catch(error) {console.error(error);fs.writeFileSync(path.join(output,'failure.png'),(await win.webContents.capturePage()).toPNG());clearTimeout(timeout);win.destroy();app.exit(1);}
});
